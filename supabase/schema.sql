-- The tables the server routes write to.
--
-- Run this once in the Supabase SQL editor, or with `supabase db push`.
-- Nothing here is required for the site to work: without these tables the
-- routes say that they are not set up, and the site carries on.

-- The global leaderboard. One row per round played.
create table if not exists public.global_scores (
  id bigint generated by default as identity primary key,
  day_key text not null,
  region text not null default 'usa',
  score numeric(8, 2) not null default 0,
  max_score numeric(8, 2) not null default 1300,
  accuracy integer not null default 0,
  streak integer not null default 0,
  nickname text not null default 'Anonymous',
  -- A hash of the device, so one device cannot fill the board. It is never
  -- connected to anything else that is stored.
  player_hash text not null,
  created_at timestamptz not null default now()
);

-- One score a day, per device, per round. A replay replaces the earlier one.
create unique index if not exists global_scores_day_region_player_idx
  on public.global_scores (day_key, region, player_hash);

-- The board is read for one day and one region, best score first.
create index if not exists global_scores_day_region_score_idx
  on public.global_scores (day_key, region, score desc);

-- The Pro licences. Filled in by the Lemon Squeezy webhook.
create table if not exists public.licenses (
  id bigint generated by default as identity primary key,
  license_key text not null unique,
  email text,
  variant_id integer,
  status text not null default 'active',
  order_id text,
  created_at timestamptz not null default now()
);

-- Questions and corrections sent in by players.
create table if not exists public.question_submissions (
  id bigint generated by default as identity primary key,
  question_text text not null,
  venue text,
  hint text,
  country text,
  latitude double precision,
  longitude double precision,
  facts text,
  submitter_email text,
  kind text not null default 'new',
  status text not null default 'new',
  created_at timestamptz not null default now()
);

-- The service role key is used by the server routes, which are the only
-- things that should see this table. The reading and writing policies for
-- anon are deliberately not created: the browser never talks to the table
-- directly, it goes through the routes.
alter table public.global_scores enable row level security;
alter table public.licenses enable row level security;
alter table public.question_submissions enable row level security;

-- The routes use the service role key, which bypasses these policies.
-- These policies exist so that a stray anon key cannot read the table.
create policy "the service role reads the board"
  on public.global_scores for select
  to service_role
  using (true);

create policy "the service role writes the board"
  on public.global_scores for insert
  to service_role
  with check (true);

-- The board is written as an upsert: one row per day, per round, per device.
-- A replay of the same day replaces the earlier row, so the write needs to be
-- able to update it as well as insert it.
create policy "the service role updates the board"
  on public.global_scores for update
  to service_role
  using (true)
  with check (true);

create policy "the service role reads the licences"
  on public.licenses for select
  to service_role
  using (true);

create policy "the service role writes the licences"
  on public.licenses for insert
  to service_role
  with check (true);

create policy "the service role reads the submissions"
  on public.question_submissions for select
  to service_role
  using (true);

create policy "the service role writes the submissions"
  on public.question_submissions for insert
  to service_role
  with check (true);

-- Private tournaments: a fixed set of questions, a code to join by and a
-- time it closes. Read and written only by the server, like the board.
create table if not exists public.tournaments (
  code text primary key,
  name text not null default 'Private tournament',
  question_ids text[] not null,
  created_by text not null default 'A friend',
  ends_at timestamptz not null,
  created_at timestamptz not null default now()
);

-- One round per device per tournament.
create table if not exists public.tournament_entries (
  id bigint generated by default as identity primary key,
  code text not null references public.tournaments (code) on delete cascade,
  player_hash text not null,
  nickname text not null default 'Anonymous',
  score numeric(8, 2) not null default 0,
  accuracy integer not null default 0,
  created_at timestamptz not null default now(),
  unique (code, player_hash)
);

create index if not exists tournament_entries_code_score_idx
  on public.tournament_entries (code, score desc);

alter table public.tournaments enable row level security;
alter table public.tournament_entries enable row level security;

create policy "the service role reads the tournaments"
  on public.tournaments for select
  to service_role
  using (true);

create policy "the service role writes the tournaments"
  on public.tournaments for insert
  to service_role
  with check (true);

create policy "the service role reads the tournament entries"
  on public.tournament_entries for select
  to service_role
  using (true);

create policy "the service role writes the tournament entries"
  on public.tournament_entries for insert
  to service_role
  with check (true);

-- The daily rounds: the ten questions of each day, written ahead of time by
-- scripts/daily/schedule.ts and handed out by /api/daily once the day starts.
create table if not exists public.daily_rounds (
  day_key text not null,
  region text not null,
  questions jsonb not null,
  created_at timestamptz not null default now(),
  primary key (day_key, region)
);

alter table public.daily_rounds enable row level security;

create policy "the service role reads the daily rounds"
  on public.daily_rounds for select
  to service_role
  using (true);

create policy "the service role writes the daily rounds"
  on public.daily_rounds for insert
  to service_role
  with check (true);
